// The picture a tile shows: null for blank, unknown or deleted ids.
export function resolveArtwork(custom: readonly ArtworkAsset[], artworkId: string | null): ArtworkAsset | null {
  if (artworkId === null) return null;
  if (artworkId.startsWith(BUILTIN_PREFIX)) return BUILTIN_ARTWORK.find((a) => a.id === artworkId) ?? null;
  return custom.find((a) => a.id === artworkId && a.source === "custom") ?? null;
}
