// When the app generates arrangements by itself, and which one it selects (CHG-0011).
// Pure: SolverPanel supplies the facts and runs the solver.
import type { SolveResult, SolvedLayout } from "../core/solver/index.ts";

export const AUTO_GENERATE_DELAY_MS = 400;

export interface AutoGenerateFacts {
  // A frame exists, every name is valid and there is at least one name.
  canGenerate: boolean;
  namesKey: string;
  // The names when this project was shown; only a change from them counts as a name edit.
  openedKey: string;
  // The names the chosen arrangement was made for; null when there is none or it does not match its names.
  appliedKey: string | null;
}

export type AutoGenerateDecision = { run: false } | { run: true; delayMs: number };

export function decideAutoGenerate(f: AutoGenerateFacts): AutoGenerateDecision {
  if (!f.canGenerate || f.namesKey === f.appliedKey) return { run: false };
  // On open there is no typing to wait for.
  return { run: true, delayMs: f.namesKey === f.openedKey ? 0 : AUTO_GENERATE_DELAY_MS };
}

// The arrangement an automatic run selects: the first in the list, none on failure.
export function firstArrangement(result: SolveResult): SolvedLayout | null {
  return result.failure ? null : (result.layouts[0] ?? null);
}
